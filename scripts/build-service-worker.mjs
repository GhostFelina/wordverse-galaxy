// Generate dist/sw.js after the build. The precache holds the small app shell
// (HTML, JS, CSS, fonts, icons); large scene assets are cached on first use with
// a bounded entry count. Cross-origin requests (Supabase, auth) are never cached.
import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const SHELL_PATTERN =
  /\.(html|js|css|woff2|webmanifest)$|^favicon\.svg$|^icons\/.+\.png$|^assets\/wordverse-mark\.svg$/;
const MAX_SHELL_FILE = 1_500_000;

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => (entry.isDirectory() ? walk(join(directory, entry.name)) : [join(directory, entry.name)])),
  );
  return files.flat();
}

export async function precacheList(root = dist) {
  const files = [];
  for (const file of await walk(root)) {
    const path = relative(root, file).split(sep).join('/');
    if (path === 'sw.js' || !SHELL_PATTERN.test(path) || (await stat(file)).size > MAX_SHELL_FILE) continue;
    files.push(path);
  }
  return files.sort().map((path) => `/${path}`);
}

export function serviceWorkerSource(version, precache) {
  return `// Generated by scripts/build-service-worker.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const SHELL = 'wordverse-shell-' + VERSION;
const ASSETS = 'wordverse-assets-v1';
const MAX_ASSET_ENTRIES = 80;
const PRECACHE = ${JSON.stringify(precache)};
const SHELL_SET = new Set(PRECACHE);

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((key) => key.startsWith('wordverse-shell-') && key !== SHELL).map((key) => caches.delete(key))),
    ).then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

function shellFor(url) {
  const locale = url.pathname.match(/^\\/(en|es)(?:\\/|$)/)?.[1];
  const page = /about\\.html$/.test(url.pathname) ? 'about.html' : 'index.html';
  return (locale ? '/' + locale + '/' : '/') + page;
}

async function trim(cache) {
  const keys = await cache.keys();
  for (const key of keys.slice(0, Math.max(0, keys.length - MAX_ASSET_ENTRIES))) await cache.delete(key);
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Network first keeps deployments fresh; the cached shell opens the app offline.
    event.respondWith(
      fetch(request).catch(async () => (await caches.match(request, { ignoreSearch: true })) || caches.match(shellFor(url))),
    );
    return;
  }
  if (SHELL_SET.has(url.pathname)) {
    event.respondWith(caches.match(url.pathname).then((hit) => hit || fetch(request)));
    return;
  }
  if (url.pathname.startsWith('/assets/') && !request.headers.has('range')) {
    event.respondWith(
      caches.open(ASSETS).then(async (cache) => {
        const hit = await cache.match(request);
        if (hit) return hit;
        const response = await fetch(request);
        if (response.ok && response.type === 'basic') {
          await cache.put(request, response.clone());
          trim(cache);
        }
        return response;
      }),
    );
  }
});
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const precache = await precacheList();
  if (!precache.includes('/index.html')) throw new Error('Build output missing index.html');
  const hash = createHash('sha256');
  for (const path of precache) hash.update(path).update(await readFile(join(dist, path.slice(1))));
  const version = hash.digest('hex').slice(0, 16);
  await writeFile(join(dist, 'sw.js'), serviceWorkerSource(version, precache), 'utf8');
  console.log(`Service worker ${version}: ${precache.length} shell files.`);
}
